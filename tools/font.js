function pack(src,h){
  const out={};
  for(const ln of src.trim().split('\n')){
    const p=ln.trim().split(/\s+/),ch=p[0],rows=p.slice(1);
    if(rows.length!==h||rows.some(r=>r.length!==rows[0].length||/[^#.]/.test(r)))throw new Error('bad glyph '+ch);
    let s='';
    for(let x=0;x<rows[0].length;x++){let v=0;for(let y=0;y<h;y++)if(rows[y][x]==='#')v|=1<<y;s+=v.toString(16).padStart(2,'0');}
    out[ch]=s;
  }
  return out;
}
